/// Calendar-day helper used by all mock datasets (see `mock_dates.dart`).
TimelineEvent _ev(int offset, String title, TimelineStepState state) =>
    TimelineEvent(date: day(offset), title: title, state: state);

/// Axis-aligned parcel boundary in WKT (lon lat) around the case centroid.
String _parcelWkt(double lat, double lng) {
  const dLat = 0.0012;
  const dLng = 0.0014;
  final n = (lat + dLat).toStringAsFixed(5);
  final s = (lat - dLat).toStringAsFixed(5);
  final e = (lng + dLng).toStringAsFixed(5);
  final w = (lng - dLng).toStringAsFixed(5);
  return 'POLYGON(($w $n, $e $n, $e $s, $w $s, $w $n))';
}
